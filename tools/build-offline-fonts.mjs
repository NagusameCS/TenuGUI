#!/usr/bin/env node
/**
 * Build data-URL font faces for opening the site directly from file://.
 * Chrome blocks font requests from an opaque file origin, but data URLs work.
 * The generated stylesheet is only loaded when location.protocol === "file:".
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fonts = [
  ["Dela Gothic One", 400, "dela-gothic.woff2"],
  ["Inter", 400, "inter-400.woff2"],
  ["Inter", 500, "inter-500.woff2"],
  ["Inter", 600, "inter-600.woff2"],
  ["IBM Plex Mono", 400, "plex-mono-400.woff2"],
  ["IBM Plex Mono", 500, "plex-mono-500.woff2"],
];
const rules = fonts.map(([family, weight, file]) => {
  const data = fs.readFileSync(path.join(root, "assets", "fonts", file)).toString("base64");
  return `@font-face{font-family:"${family}";src:url("data:font/woff2;base64,${data}") format("woff2");font-weight:${weight};font-style:normal;font-display:swap;}`;
});
const out = `/* Generated by tools/build-offline-fonts.mjs. */\n${rules.join("\n")}\n`;
fs.writeFileSync(path.join(root, "assets", "css", "offline-fonts.css"), out);
console.log("  ✓ assets/css/offline-fonts.css");

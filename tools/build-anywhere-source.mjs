#!/usr/bin/env node
/**
 * Build the browser-button source bundle.
 *
 * bookmarklet.html can load this classic script from file:// as well as from a
 * web server, then encode the string into the draggable javascript: bookmarklet.
 * Run after editing assets/js/anywhere.js.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "assets", "js", "anywhere.js");
const outPath = path.join(root, "assets", "js", "anywhere-source.js");
const source = fs.readFileSync(sourcePath, "utf8");
const encoded = JSON.stringify(source).replace(/</g, "\\u003c");
const body = `/* Generated by tools/build-anywhere-source.mjs — edit assets/js/anywhere.js instead. */\nwindow.__TENUGUI_ANYWHERE_SOURCE = ${encoded};\n`;
fs.writeFileSync(outPath, body);
console.log(`  ✓ ${path.relative(root, outPath)}`);
